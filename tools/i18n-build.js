#!/usr/bin/env node
/*
 * Builds the MEIKO translation files from i18n/en.txt (English source, one string per line) and
 * i18n/translations.txt (lines "n|id|ms|tl|vi|th|zh", n = 0-based line in en.txt, empty = keep English).
 * Writes js/lang/strings.js and js/lang/<code>.js. Run: node tools/i18n-build.js
 * To add a string: append it to en.txt, add a line to translations.txt with the next number, rebuild,
 * and bump CACHE_VERSION in service-worker.js.
 */
'use strict';
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const CODES = ['id', 'ms', 'tl', 'vi', 'th', 'zh'];

const en = fs.readFileSync(path.join(root, 'i18n/en.txt'), 'utf8').replace(/\n$/, '').split('\n');
const lists = {}; CODES.forEach(c => lists[c] = new Array(en.length).fill(''));
let errors = 0, warns = 0;
const err = m => { errors++; console.error('ERROR ' + m); };
const warn = m => { warns++; if (process.argv.includes('-v')) console.warn('warn  ' + m); };

const seen = new Set();
fs.readFileSync(path.join(root, 'i18n/translations.txt'), 'utf8').split('\n').forEach((line, ln) => {
  if (!line.trim() || line[0] === '#') return;
  const f = line.split('|');
  if (f.length !== CODES.length + 1) return err('translations.txt:' + (ln + 1) + ' has ' + f.length + ' fields');
  const n = +f[0];
  if (!Number.isInteger(n) || n < 0 || n >= en.length) return err('translations.txt:' + (ln + 1) + ' bad index ' + f[0]);
  if (seen.has(n)) return err('duplicate index ' + n); seen.add(n);
  const nums = (en[n].match(/\d+(?:[.,]\d+)?/g) || []).map(x => x.replace(',', '.'));
  CODES.forEach((c, i) => {
    const t = f[i + 1].trim(); if (!t) return;
    lists[c][n] = t;
    const tn = (t.match(/\d+(?:[.,]\d+)?/g) || []).map(x => x.replace(',', '.'));
    nums.forEach(x => { if (!tn.includes(x)) warn(c + ' #' + n + ' missing number ' + x + ': ' + t); });
  });
});
for (let i = 0; i < en.length; i++) if (!seen.has(i)) warn('no translation line for #' + i + ': ' + en[i]);
if (errors) { console.error(errors + ' error(s); nothing written.'); process.exit(1); }

const out = path.join(root, 'js/lang'); fs.mkdirSync(out, { recursive: true });
const head = '/* Generated by tools/i18n-build.js from i18n/. Do not edit by hand. */\n';
fs.writeFileSync(path.join(out, 'strings.js'), head + 'MEIKO.i18n.SRC=' + JSON.stringify(en) + ';\n');
CODES.forEach(c => {
  let last = lists[c].length; while (last && !lists[c][last - 1]) last--;
  fs.writeFileSync(path.join(out, c + '.js'), head + 'MEIKO.i18n.add(' + JSON.stringify(c) + ',' + JSON.stringify(lists[c].slice(0, last)) + ');\n');
  console.log(c + ': ' + lists[c].filter(Boolean).length + '/' + en.length);
});
console.log('Done' + (warns ? ' (' + warns + ' warnings, run with -v to list)' : '') + '.');
